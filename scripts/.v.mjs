import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true, args: ["--use-angle=gl-egl", "--ignore-gpu-blocklist", "--enable-gpu"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const shot = (n) => page.screenshot({ path: `output/startup-city/v-${n}.png` });
await page.goto("http://127.0.0.1:5179/?nointro");
await page.waitForFunction(() => !!window.__startupCity?.scene && window.__startupCity.store.getState().loaded, null, { timeout: 120000 });
await page.evaluate(() => window.__startupCity.store.getState().setTime({ live: false, minutes: 22 * 60 }));
await page.click("#enter");
await page.waitForTimeout(1500); await shot("1-opening-sky");
await page.waitForTimeout(4500); await shot("2-opening-descent");
await page.waitForFunction(() => !document.body.classList.contains("sc-opening"), null, { timeout: 20000 });
await page.waitForTimeout(800); await shot("3-landed");
await page.evaluate(() => window.__startupCity.scene.flyTo({ tx: 900, tz: 900, dist: 200 }, 0.01));
await page.waitForTimeout(800);
await page.click(".sc-filters >> text=Health");
await page.waitForTimeout(2500); await shot("4-filter-framed");
await page.click(".sc-result >> text=Clear filters");
await page.evaluate(() => { const st = window.__startupCity.store.getState(); const a = st.startups.find((s) => s.id === "supercell"); st.select(a.location.buildingId, a.id, null); st.setMode("street"); st.select(null); });
await page.waitForFunction(() => window.__webworldEngine.getSnapshot().state === "ride", null, { timeout: 30000 });
await page.waitForTimeout(1000);
await page.evaluate(() => window.__startupCity.store.getState().navigateTo("saidot"));
await page.waitForTimeout(1500); await shot("5-street-route");
await page.click(".sc-route-bar >> text=Overview");
await page.waitForTimeout(2500); await shot("6-route-overview");
await page.click(".sc-route-bar >> text=Clear");
console.log("route after clear", await page.evaluate(() => window.__startupCity.store.getState().route));
await page.click('button[aria-label="Settings"]'); await page.waitForTimeout(400); await shot("7-settings");
console.log("errors", errors);
await browser.close();
